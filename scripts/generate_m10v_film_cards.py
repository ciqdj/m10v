def generate():
 names=re.findall(r'\{"([^"\n]+)",[-0-9]',(ROOT/'native/gr3/m10v_library.c').read_text())
 names += [v['name'] for v in json.loads((ROOT/'web/gr3/film-catalog.json').read_text())['looks']]
 names += ['5207','蓝凤凰','哈曼 RED','Portra 160','富士业务用 100','乐凯 C200','CCD Classic']
 if len(names)!=72:raise ValueError('film catalog differs')
 rows=['/* Generated by scripts/generate_m10v_film_cards.py. */',
       'static const struct { char main[6], sub[6]; uint32_t color, ink; } cards[72]={']
 for i,name in enumerate(names,1):
  title,code,color=label(name,i);main,sub=code or title,title if code else ''
  if name=='5207' or name=='V3 5207':main,sub,color='5207','250D','#00a5d2'
  if name=='800T':main,sub,color='800T','CINE','#169ac9'
  if name=='Gold 200':main,sub,color='G200','GOLD','#f6cb33'
  if name=='Ektar 100':main,sub,color='E100','EKTAR','#e92a40'
  if name=='Pro 400H':main,sub,color='400H','FUJI','#29ad79'
  if name=='蓝凤凰':main,sub,color='PHNX','II200','#397ac4'
  if name=='哈曼 RED':main,sub,color='RED','125','#e04439'
  ink='0xff244975u' if name=='Gold 200' else '0xfff3faf9u'
  rows.append(f' {{"{main}","{sub}",0xff{color[1:]}u,{ink}}},')
 rows+=['};','static const uint8_t card_glyphs[36][5]={']
 for char in '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ':
  rows.append(' {'+','.join(str(int(row,2)) for row in GLYPHS[char])+'},')
 rows+=['};','static const uint8_t card_large_glyphs[36][7]={']
 for char in '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ':
  rows.append(' {'+','.join(str(int(row,2)) for row in GLYPHS5[char])+'},')
 rows+=['};','']
 return '\n'.join(rows)
if __name__=='__main__':(ROOT/'native/gr3/m10v_film_card_data.h').write_text(generate())
