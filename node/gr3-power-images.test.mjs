import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {decodeFrameMap,sum32} from './gr3-frames.mjs';
const module=await import('./gr3-power-images.mjs').catch(()=>({}));
test('shutdown export installs A-drive JPEG and all five factory shutdown requests, with fresh container readback',()=>{
 assert.equal(typeof module.applyPowerImages,'function','power-image builder is required');
 const source=readFileSync(new URL('../bin/fwdc239b-gr3-official.bin',import.meta.url));
 const original=decodeFrameMap(source).decoded;
 const image=original.subarray(59298689,59298689+112509);
 const config={shutdown:{jpeg_base64:image.toString('base64')}};
 const prepared=module.preparePowerImages(source,config);
 assert.equal(prepared.shutdown.enabled,true);assert.equal(prepared.startup.display_verified,false);
 const {candidate,receipt}=module.applyPowerImages(source,source,config);
 const actual=decodeFrameMap(candidate).decoded;
 assert.equal(sum32(candidate),0);assert.equal(sum32(actual),0);
 assert.equal(actual.length,original.length);
 assert.equal(actual.toString('ascii',59298653,59298653+29),'A:\\Resource\\Jpeg\\GB_Diary.jpg');
 assert.equal(actual[0x10870+0xb2298c],65);
 for(const index of [1,2,9,10,11])assert.equal(actual.readUInt32LE(0x10870+0x107e0bc+index*4),0x53b5f508);
 assert.equal(receipt.shutdown.jpeg_sha256,prepared.shutdown.jpeg_sha256);
 assert.equal(receipt.camera_tested,false);assert.equal(receipt.non_target_bytes_unchanged,true);
 assert.ok(actual.subarray(59298689,59298689+112509).includes(Buffer.from([0xff,0xc0])));
 assert.notDeepEqual(candidate,source);
 assert.deepEqual(module.applyPowerImages(source,source,{}).candidate,source);
});
test('power images reject wrong models and malformed JPEG data, with unchanged hashes for defaults',()=>{
 assert.equal(typeof module.preparePowerImages,'function');
 const source=readFileSync(new URL('../bin/fwdc239b-gr3-official.bin',import.meta.url));
 assert.throws(()=>module.preparePowerImages(source,{startup:{jpeg_base64:'abcd'}}),/JPEG|图片/);
 const decoded=decodeFrameMap(source).decoded;const truncated=decoded.subarray(59298689,59298689+10000);
 assert.throws(()=>module.preparePowerImages(source,{shutdown:{jpeg_base64:truncated.toString('base64')}}),/JPEG|图片/);
 assert.throws(()=>module.preparePowerImages(source,{shutdown:{jpeg_base64:Buffer.from('not jpeg').toString('base64')}}),/JPEG|图片/);
 const x=readFileSync(new URL('../bin/fwdc243b-gr3x-official.bin',import.meta.url));
 assert.throws(()=>module.preparePowerImages(x,{shutdown:{jpeg_base64:'abcd'}}),/JPEG|图片/);
 const base={configuration_sha256:'a'.repeat(64),ready:true};
 assert.equal(module.bindPowerPreparation(base,source,{}).configuration_sha256,base.configuration_sha256);
});
test('startup and shutdown remain independent slots and startup request 1 is never aliased',()=>{
 const source=readFileSync(new URL('../bin/fwdc239b-gr3-official.bin',import.meta.url)),original=decodeFrameMap(source).decoded;
 const jpeg=original.subarray(59298689,59298689+112509).toString('base64');
 const startupOnly=module.applyPowerImages(source,source,{startup:{jpeg_base64:jpeg}}),both=module.applyPowerImages(source,source,{startup:{jpeg_base64:jpeg},shutdown:{jpeg_base64:jpeg}});
 const a=decodeFrameMap(startupOnly.candidate).decoded,b=decodeFrameMap(both.candidate).decoded;
 assert.equal(a.readUInt32LE(0x10870+0x107e0bc),0x53b5f520);assert.equal(b.readUInt32LE(0x10870+0x107e0bc),0x53b5f520);
 assert.ok(a.subarray(59298689,59298689+112509).equals(original.subarray(59298689,59298689+112509)));
 assert.equal(a[0x10870+0xb22adc],65);assert.equal(b[0x10870+0xb2298c],65);
 const prep={configuration_sha256:'a'.repeat(64),ready:true};
 const startupPlan=module.bindPowerPreparation(prep,source,{startup:{jpeg_base64:jpeg}}),bothPlan=module.bindPowerPreparation(prep,source,{startup:{jpeg_base64:jpeg},shutdown:{jpeg_base64:jpeg}});
 assert.notEqual(startupPlan.configuration_sha256,prep.configuration_sha256);assert.notEqual(startupPlan.configuration_sha256,bothPlan.configuration_sha256);
 assert.equal(startupPlan.power_images.startup.display_verified,false);
});
